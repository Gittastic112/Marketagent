import base64
import hashlib
import hmac
import json
import logging
import time
from typing import Optional

from fastapi import Depends, HTTPException, Request, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.db.session import get_db
from app.models.user import User

logger = logging.getLogger(__name__)
security = HTTPBearer(auto_error=False)

INTERNAL_USER_HEADER = "x-market-intel-user"
INTERNAL_SIGNATURE_HEADER = "x-market-intel-signature"
INTERNAL_AUTH_MAX_AGE_SECONDS = 60
INTERNAL_AUTH_FUTURE_SKEW_SECONDS = 30


def _not_authenticated() -> HTTPException:
    return HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Not authenticated",
    )


async def get_current_user(
    request: Request,
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(security),
    db: Session = Depends(get_db),
) -> dict:
    """Validate the short-lived identity assertion generated by the Next.js server."""
    del credentials  # Bearer-token authentication is not implemented for this local-only flow.

    encoded_payload = request.headers.get(INTERNAL_USER_HEADER)
    supplied_signature = request.headers.get(INTERNAL_SIGNATURE_HEADER)
    if not encoded_payload or not supplied_signature:
        raise _not_authenticated()

    secret = get_settings().nextauth_secret
    if not secret:
        logger.error("Backend authentication is unavailable because NEXTAUTH_SECRET is unset")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Authentication is not configured",
        )

    expected_signature = hmac.new(
        secret.encode("utf-8"),
        encoded_payload.encode("ascii"),
        hashlib.sha256,
    ).hexdigest()
    if not hmac.compare_digest(supplied_signature, expected_signature):
        raise _not_authenticated()

    try:
        padding = "=" * (-len(encoded_payload) % 4)
        decoded_payload = base64.urlsafe_b64decode(encoded_payload + padding)
        identity = json.loads(decoded_payload.decode("utf-8"))
        user_id = str(identity.get("sub") or "")
        issued_at = int(identity.get("iat"))
    except (UnicodeError, ValueError, TypeError, json.JSONDecodeError):
        raise _not_authenticated() from None

    now = int(time.time())
    if (
        not user_id
        or issued_at < now - INTERNAL_AUTH_MAX_AGE_SECONDS
        or issued_at > now + INTERNAL_AUTH_FUTURE_SKEW_SECONDS
    ):
        raise _not_authenticated()

    user = {
        "id": user_id,
        "email": identity.get("email") or f"{user_id}@local.invalid",
        "name": identity.get("name") or "Local User",
    }
    if db.get(User, user_id) is None:
        db.add(User(id=user_id, email=user["email"], name=user["name"]))
        try:
            db.commit()
        except IntegrityError:
            db.rollback()
            if db.get(User, user_id) is None:
                raise _not_authenticated() from None
    return user
