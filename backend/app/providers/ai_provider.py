import httpx
import logging
import re
import json
import time
from app.providers.base import BaseAIProvider, AIProviderResult
from app.providers.safe_http import read_bounded_response

logger = logging.getLogger(__name__)
DEFAULT_GEMINI_MODEL = "gemini-2.5-flash"


class GeminiRequestError(RuntimeError):
    """Safe provider failure, with no request, body or credential attached."""

    def __init__(self, message: str, status_code: int | None = None):
        super().__init__(message)
        self.status_code = status_code


def _response_text(data: dict) -> str:
    try:
        candidate = data["candidates"][0]
        if candidate.get("finishReason", "STOP") != "STOP":
            raise ValueError("AI provider response was incomplete or blocked")
        output_text = "".join(
            part["text"] for part in candidate["content"]["parts"]
            if isinstance(part, dict) and isinstance(part.get("text"), str)
            and not part.get("thought", False)
        )
    except (KeyError, IndexError, TypeError) as exc:
        raise ValueError("AI provider response did not contain generated text") from exc
    if not isinstance(output_text, str) or not output_text.strip():
        raise ValueError("AI provider response did not contain generated text")
    return output_text.strip()

class GeminiAIProvider(BaseAIProvider):
    """Gemini-based AI provider implementation."""

    def __init__(self, api_key: str, model_name: str = DEFAULT_GEMINI_MODEL):
        if not re.fullmatch(r"gemini-[A-Za-z0-9._-]{1,80}", model_name):
            raise ValueError("Invalid Gemini model identifier")
        self.api_key = api_key.strip()
        self.model_name = model_name

    def _generate(self, payload: dict, *, failure_message: str) -> AIProviderResult:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent"
        try:
            started = time.monotonic()
            with httpx.Client(trust_env=False, follow_redirects=False, timeout=20.0) as client:
                with client.stream("POST", url,
                    headers={"x-goog-api-key": self.api_key, "Accept-Encoding": "identity"}, json=payload) as response:
                    data = json.loads(read_bounded_response(response, max_bytes=2 * 1024 * 1024, started=started))
            return AIProviderResult(
                model_name=self.model_name,
                output_text=_response_text(data),
                limitations="Generated by an AI model. May contain inaccuracies or hallucinations. Not financial advice.",
                confidence_label="Medium",
            )
        except Exception as exc:
            status_code = exc.response.status_code if isinstance(exc, httpx.HTTPStatusError) else None
            logger.error(failure_message, extra={"provider": self.provider_name, "exception_type": type(exc).__name__})
            raise GeminiRequestError(failure_message, status_code=status_code) from None

    def check_connection(self) -> AIProviderResult:
        """A bounded fixed prompt, never a user's portfolio or research content."""
        return self._generate({
            "contents": [{"parts": [{"text": "Reply exactly OK."}]}],
            "generationConfig": {"maxOutputTokens": 256},
        }, failure_message="AI connectivity check failed")

    def generate_summary(self, text: str) -> AIProviderResult:
        prompt = f"Summarize the following financial document, highlighting key changes, risks, and forward-looking statements. Be concise.\n\n{text[:10000]}"

        payload = {
            "contents": [{"parts": [{"text": prompt}]}]
        }

        return self._generate(payload, failure_message="AI summary request failed")

    def generate_chat_response(self, messages: list[dict], context: str = "") -> AIProviderResult:

        system_instruction = (
            "You are a serious, analytical financial research assistant. "
            "You must strictly follow these formatting rules for every response:\n"
            "1. Do not invent sources. If you don't know, say so.\n"
            "2. Always structure your response with these clear sections:\n"
            "   **Claim:** (What is the answer/insight)\n"
            "   **Reasoning:** (Why you think this)\n"
            "   **Evidence:** (What data supports this, refer to provided context if any)\n"
            "   **Confidence:** (Low/Medium/High)\n"
            "   **Contradictory Evidence:** (If any)\n"
        )

        formatted_messages = []
        for msg in messages:
            role = "model" if msg["role"] == "assistant" else "user"
            formatted_messages.append({
                "role": role,
                "parts": [{"text": msg["content"]}]
            })

        payload = {
            "system_instruction": {"parts": [{"text": system_instruction}]},
            "contents": formatted_messages
        }

        return self._generate(payload, failure_message="AI chat request failed")

    def generate_structured_response(self, prompt: str, schema: dict) -> AIProviderResult:

        # We pass the schema in the generationConfig so Gemini enforces JSON structure
        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {
                "responseMimeType": "application/json",
                "responseSchema": schema
            }
        }

        return self._generate(payload, failure_message="AI structured response request failed")

    @property
    def provider_name(self) -> str:
        return "gemini"
